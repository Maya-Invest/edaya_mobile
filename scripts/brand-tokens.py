#!/usr/bin/env python3
"""Generate/check local EDAYA tokens. No network or sibling checkout required."""
import argparse
import colorsys
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
WEB = (ROOT / 'apps/webapp').is_dir()
MANIFEST = ROOT / ('design-system/tokens.json' if WEB else
                   'packages/edaya_shared/design-system/tokens.json')


def camel(value):
    parts = value.split('-')
    return parts[0] + ''.join(part.title() for part in parts[1:])


def outputs(tokens):
    if WEB:
        lines = ['/* Generated by scripts/brand-tokens.py. Edit the manifest. */', ':root {']
        for name, color in tokens['colors']['light'].items():
            rgb = [int(color[i:i + 2], 16) / 255 for i in (1, 3, 5)]
            h, lightness, saturation = colorsys.rgb_to_hls(*rgb)
            lines.append(f'\t--{name}: {h * 360:.4f} {saturation * 100:.4f}% {lightness * 100:.4f}%;')
        for group in ('space', 'radius', 'motion'):
            unit = 'ms' if group == 'motion' else 'px'
            lines += [f'\t--{group}-{name}: {value}{unit};' for name, value in tokens[group].items()]
        lines += ['\t--radius: var(--radius-base);',
                  "\t--font-display: 'Poppins', ui-sans-serif, system-ui, sans-serif;",
                  "\t--font-sans: 'Inter', ui-sans-serif, system-ui, sans-serif;",
                  '\t--font-mono: ui-monospace, monospace;', '}', '']
        return {ROOT / 'apps/webapp/src/lib/design-system/tokens.css': '\n'.join(lines)}
    lines = ['// Generated by scripts/brand-tokens.py. Edit the manifest.',
             "import 'package:flutter/material.dart';", '',
             'abstract final class EdayaTokens {',
             f"  static const version = '{tokens['version']}';"]
    for mode, colors in tokens['colors'].items():
        for name, color in colors.items():
            key = camel(name)
            lines.append(f'  static const {mode}{key[0].upper()}{key[1:]} = Color(0xFF{color[1:]});')
    for group in ('type', 'space', 'radius', 'motion'):
        for name, value in tokens[group].items():
            lines.append(f'  static const {group}{name[0].upper()}{name[1:]} = {value}.0;')
    lines += ["  static const headingFont = 'Poppins';", "  static const bodyFont = 'Inter';", '}', '']
    return {ROOT / 'packages/edaya_shared/lib/src/app/edaya_tokens.g.dart': '\n'.join(lines)}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    parser.add_argument('--sync-from', type=Path,
                        help='Explicitly import a reviewed manifest from the canonical frontend repo')
    args = parser.parse_args()
    if args.sync_from:
        if args.check:
            parser.error('--check cannot write a snapshot')
        source = json.loads(args.sync_from.read_text())
        MANIFEST.write_text(json.dumps(source, indent=2) + '\n')
    tokens = json.loads(MANIFEST.read_text())
    failed = []
    for path, expected in outputs(tokens).items():
        if args.check:
            if not path.exists() or path.read_text() != expected:
                failed.append(str(path.relative_to(ROOT)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(expected)
    if failed:
        print('EDAYA token drift: ' + ', '.join(failed), file=sys.stderr)
        return 1
    print(f"EDAYA {tokens['version']}: {'checked' if args.check else 'generated'} {'web' if WEB else 'Flutter'} tokens")
    return 0


if __name__ == '__main__':
    sys.exit(main())

import 'dart:convert';
import 'dart:io';

const bindingsExtension = 'x-edaya-client-bindings';
const kindExtension = 'x-edaya-kind';
const entityKeyExtension = 'x-edaya-entity-key';
const entityPublicNameExtension = 'x-edaya-entity-public-name';
const responseSchemaExtension = 'x-edaya-response-schema';
const allowDirectSaveExtension = 'x-edaya-allow-direct-save';
const commandKeyExtension = 'x-edaya-command-key';
const commandPublicNameExtension = 'x-edaya-command-public-name';
const requestSchemaExtension = 'x-edaya-request-schema';
const queryKeyExtension = 'x-edaya-query-key';
const queryPublicNameExtension = 'x-edaya-query-public-name';
const clientKeyExtension = 'x-edaya-client-key';
const clientPathExtension = 'x-edaya-client-path';
const pathParamsExtension = 'x-edaya-path-params';
const basePathExtension = 'x-edaya-base-path';
const responseIsArrayExtension = 'x-edaya-response-is-array';
const namespaceKeyExtension = 'x-edaya-namespace-key';
const coreBindingKeys = ['entities', 'commands', 'queries'];
const httpMethods = ['get', 'post', 'put', 'patch', 'delete'];
const generatedHeader =
    '// This file is auto-generated by packages/edaya_api_client/tool/generate_api_bindings.dart\n'
    '// Do not edit manually.\n';

Future<void> main(List<String> args) async {
  final options = _parseArgs(args);
  final bindings = await _loadBindings(options);
  final outputDir = Directory(options.outputDir);
  if (!outputDir.existsSync()) {
    outputDir.createSync(recursive: true);
  }

  final bindingsPath = options.bindingsPath;
  if (bindingsPath != null) {
    await File(
      bindingsPath,
    ).writeAsString(const JsonEncoder.withIndent('  ').convert(bindings));
  }

  await File(
    '${outputDir.path}/client_bindings.dart',
  ).writeAsString(_generateBindingsDart(bindings));
  await File(
    '${outputDir.path}/school_client_surface.dart',
  ).writeAsString(_generateSurfaceDart(bindings));

  stdout.writeln('Dart API client bindings generated at ${outputDir.path}');
}

class _Options {
  const _Options({
    required this.outputDir,
    this.openApiPath,
    this.openApiUrl,
    this.bindingsPath,
    this.bindingsInputPath,
  });

  final String outputDir;
  final String? openApiPath;
  final String? openApiUrl;
  final String? bindingsPath;
  final String? bindingsInputPath;
}

_Options _parseArgs(List<String> args) {
  String? openApiPath;
  String? openApiUrl;
  String? bindingsPath;
  String? bindingsInputPath;
  var outputDir = 'lib/src/generated';

  for (var index = 0; index < args.length; index++) {
    final arg = args[index];
    switch (arg) {
      case '--openapi':
        openApiPath = _requireValue(args, index, arg);
        index++;
      case '--openapi-url':
        openApiUrl = _requireValue(args, index, arg);
        index++;
      case '--bindings-input':
        bindingsInputPath = _requireValue(args, index, arg);
        index++;
      case '--bindings':
        bindingsPath = _requireValue(args, index, arg);
        index++;
      case '--output-dir':
        outputDir = _requireValue(args, index, arg);
        index++;
      default:
        throw ArgumentError('Unknown argument: $arg');
    }
  }

  if (openApiPath == null && openApiUrl == null && bindingsInputPath == null) {
    throw ArgumentError(
      'Provide --openapi <path>, --openapi-url <url>, or --bindings-input <path>',
    );
  }

  if (openApiPath != null && openApiUrl != null) {
    throw ArgumentError('Use only one of --openapi or --openapi-url');
  }

  return _Options(
    outputDir: outputDir,
    openApiPath: openApiPath,
    openApiUrl: openApiUrl,
    bindingsPath: bindingsPath,
    bindingsInputPath: bindingsInputPath,
  );
}

String _requireValue(List<String> args, int index, String flag) {
  if (index + 1 >= args.length) {
    throw ArgumentError('$flag requires a value');
  }
  return args[index + 1];
}

Future<Map<String, dynamic>> _loadBindings(_Options options) async {
  if (options.bindingsInputPath != null) {
    return _readBindingsFile(options.bindingsInputPath!);
  }

  final openApi = options.openApiUrl != null
      ? await _readOpenApiFromUrl(options.openApiUrl!)
      : await _readOpenApiFromFile(options.openApiPath!);

  return _extractBindings(openApi);
}

Future<Map<String, dynamic>> _readOpenApiFromFile(String path) async {
  final openApiFile = File(path);
  if (!openApiFile.existsSync()) {
    throw StateError('OpenAPI spec not found: ${openApiFile.path}');
  }

  return jsonDecode(await openApiFile.readAsString()) as Map<String, dynamic>;
}

Future<Map<String, dynamic>> _readOpenApiFromUrl(String url) async {
  final client = HttpClient();
  try {
    final request = await client.getUrl(Uri.parse(url));
    final response = await request.close();
    if (response.statusCode < 200 || response.statusCode >= 300) {
      throw HttpException(
        'Failed to download OpenAPI spec: HTTP ${response.statusCode}',
        uri: Uri.parse(url),
      );
    }

    final body = await response.transform(utf8.decoder).join();
    return jsonDecode(body) as Map<String, dynamic>;
  } finally {
    client.close(force: true);
  }
}

Map<String, dynamic> _extractBindings(Map<String, dynamic> openApi) {
  final bindings = <String, dynamic>{
    'entities': <String, dynamic>{},
    'commands': <String, dynamic>{},
    'queries': <String, dynamic>{},
  };

  final paths = openApi['paths'];
  if (paths is Map<String, dynamic>) {
    for (final pathItem in paths.values) {
      if (pathItem is! Map<String, dynamic>) {
        continue;
      }

      for (final method in httpMethods) {
        final operation = pathItem[method];
        if (operation is! Map<String, dynamic>) {
          continue;
        }

        final kind = operation[kindExtension];
        if (kind == 'entity') {
          final key = _readString(operation, entityKeyExtension);
          bindings['entities'][key] = {
            'publicName': _readString(operation, entityPublicNameExtension),
            'schemaName': _readString(operation, responseSchemaExtension),
            'publicOperations': _readPublicOperations(operation),
            'allowDirectSave': _readBoolean(
              operation,
              allowDirectSaveExtension,
              fallback: true,
            ),
          };
          continue;
        }

        if (kind == 'command') {
          final key = _readString(operation, commandKeyExtension);
          bindings['commands'][key] = {
            'publicName': _readString(operation, commandPublicNameExtension),
            'requestSchemaName': _readString(operation, requestSchemaExtension),
            'responseSchemaName': _readString(
              operation,
              responseSchemaExtension,
            ),
          };
          continue;
        }

        if (kind == 'query') {
          final key = _readString(operation, queryKeyExtension);
          bindings['queries'][key] = {
            'publicName': _readString(operation, queryPublicNameExtension),
            'requestSchemaName': _readString(operation, requestSchemaExtension),
            'responseSchemaName': _readString(
              operation,
              responseSchemaExtension,
            ),
          };
          continue;
        }

        if (_isNamespaceKind(kind)) {
          final namespace = kind == 'namespace'
              ? _readString(operation, namespaceKeyExtension)
              : kind as String;
          final key = _readString(operation, clientKeyExtension);
          final namespaceBindings =
              bindings.putIfAbsent(namespace, () => <String, dynamic>{})
                  as Map<String, dynamic>;
          namespaceBindings[key] = _extractNamespaceRouteBinding(
            method.toUpperCase(),
            operation,
          );
        }
      }
    }
  }

  final entities = bindings['entities'] as Map<String, dynamic>;
  if (entities.isEmpty) {
    final info = openApi['info'];
    if (info is Map<String, dynamic>) {
      final legacy = info[bindingsExtension];
      if (legacy is Map<String, dynamic>) {
        return _mergeLegacyBindings(bindings, legacy);
      }
    }

    throw StateError(
      'OpenAPI spec has no x-edaya-kind entity operations. '
      'Export the API spec after annotating core routes.',
    );
  }

  return bindings;
}

bool _isNamespaceKind(Object? kind) {
  return kind is String &&
      kind != 'entity' &&
      kind != 'command' &&
      kind != 'query';
}

String _readString(Map<String, dynamic> operation, String key) {
  final value = operation[key];
  if (value is! String || value.isEmpty) {
    throw StateError('OpenAPI operation is missing string field $key');
  }
  return value;
}

String? _readOptionalString(Map<String, dynamic> operation, String key) {
  final value = operation[key];
  if (value == null) {
    return null;
  }
  if (value is! String || value.isEmpty) {
    throw StateError('OpenAPI operation field $key must be a non-empty string');
  }
  return value;
}

bool _readBoolean(
  Map<String, dynamic> operation,
  String key, {
  required bool fallback,
}) {
  final value = operation[key];
  if (value == null) {
    return fallback;
  }
  if (value is! bool) {
    throw StateError('OpenAPI operation field $key must be a boolean');
  }
  return value;
}

List<String>? _readStringArray(Map<String, dynamic> operation, String key) {
  final value = operation[key];
  if (value == null) {
    return null;
  }
  if (value is! List ||
      value.any((entry) => entry is! String || entry.isEmpty)) {
    throw StateError('OpenAPI operation field $key must be a string array');
  }
  return value.cast<String>();
}

Map<String, dynamic> _extractNamespaceRouteBinding(
  String method,
  Map<String, dynamic> operation,
) {
  final binding = <String, dynamic>{
    'method': method,
    'path': _readString(operation, clientPathExtension),
  };

  final pathParams = _readStringArray(operation, pathParamsExtension);
  if (pathParams != null && pathParams.isNotEmpty) {
    binding['pathParams'] = pathParams;
  }

  final requestSchemaName = _readOptionalString(
    operation,
    requestSchemaExtension,
  );
  if (requestSchemaName != null) {
    binding['requestSchemaName'] = requestSchemaName;
  }

  final responseSchemaName = _readOptionalString(
    operation,
    responseSchemaExtension,
  );
  if (responseSchemaName != null) {
    binding['responseSchemaName'] = responseSchemaName;
  }

  final basePath = _readOptionalString(operation, basePathExtension);
  if (basePath != null) {
    if (basePath != 'core' && basePath != 'root') {
      throw StateError(
        'OpenAPI operation field $basePathExtension must be "core" or "root"',
      );
    }
    binding['basePath'] = basePath;
  }

  if (_readBoolean(operation, responseIsArrayExtension, fallback: false)) {
    binding['responseIsArray'] = true;
  }

  return binding;
}

Map<String, dynamic> _mergeLegacyBindings(
  Map<String, dynamic> bindings,
  Map<String, dynamic> legacy,
) {
  final merged = Map<String, dynamic>.from(bindings);

  for (final entry in legacy.entries) {
    final value = entry.value;
    if (value is! Map<String, dynamic>) {
      continue;
    }

    if (coreBindingKeys.contains(entry.key)) {
      final target = merged[entry.key];
      if (target is Map<String, dynamic>) {
        target.addAll(value);
      }
      continue;
    }

    final namespaceBindings =
        merged.putIfAbsent(entry.key, () => <String, dynamic>{})
            as Map<String, dynamic>;
    namespaceBindings.addAll(value);
  }

  return merged;
}

Future<Map<String, dynamic>> _readBindingsFile(String path) async {
  final bindings = jsonDecode(await File(path).readAsString());
  if (bindings is! Map<String, dynamic>) {
    throw StateError('Bindings file must contain a JSON object: $path');
  }
  return bindings;
}

Map<String, bool> _readPublicOperations(Map<String, dynamic> operation) {
  final value = operation['x-edaya-public-operations'];
  const keys = [
    'create',
    'update',
    'delete',
    'batchCreate',
    'batchUpdate',
    'batchDelete',
  ];
  if (value is! Map || keys.any((key) => value[key] is! bool)) {
    throw StateError(
      'Entity metadata requires explicit x-edaya-public-operations; re-export the backend contract',
    );
  }
  return {for (final key in keys) key: value[key] as bool};
}

String _generateBindingsDart(Map<String, dynamic> bindings) {
  final entities = _entityMap(bindings['entities']);
  final commands = _stringMap(bindings['commands'], 'publicName');
  final queries = _stringMap(bindings['queries'], 'publicName');

  final entityEntries = entities.entries
      .map((entry) {
        final binding = entry.value;
        final operations = Map<String, dynamic>.from(
          binding['publicOperations'] as Map,
        );
        final operationFields = operations.entries
            .map((entry) => '${_dartString(entry.key)}: ${entry.value == true}')
            .join(', ');
        return '''    ${_dartString(entry.key)}: EntityBinding(
      publicName: ${_dartString(binding['publicName'] as String)},
      schemaName: ${_dartString(binding['schemaName'] as String)},
      allowDirectSave: ${binding['allowDirectSave'] == true},
      publicOperations: {$operationFields},
    ),''';
      })
      .join('\n');

  final commandEntries = commands.entries
      .map(
        (entry) =>
            '    ${_dartString(entry.key)}: ${_dartString(entry.value)},',
      )
      .join('\n');

  final queryEntries = queries.entries
      .map(
        (entry) =>
            '    ${_dartString(entry.key)}: ${_dartString(entry.value)},',
      )
      .join('\n');

  return '''$generatedHeader
class EntityBinding {
  const EntityBinding({
    required this.publicName,
    required this.schemaName,
    required this.allowDirectSave,
    required this.publicOperations,
  });

  final String publicName;
  final String schemaName;
  final bool allowDirectSave;
  final Map<String, bool> publicOperations;
}

abstract final class ClientBindings {
  static const entities = <String, EntityBinding>{
$entityEntries
  };

  static const commands = <String, String>{
$commandEntries
  };

  static const queries = <String, String>{
$queryEntries
  };
}
''';
}

String _generateSurfaceDart(Map<String, dynamic> bindings) {
  final entities = _entityMap(bindings['entities']);
  final commands = _stringMap(bindings['commands'], 'publicName');
  final queries = _stringMap(bindings['queries'], 'publicName');
  final publicRoutes = _routeMap(bindings['public']);

  final entityGetters = entities.keys
      .map(
        (key) => '  EntityResource get $key => entities[${_dartString(key)}]!;',
      )
      .join('\n\n');

  final commandMethods = commands.entries
      .map(
        (entry) =>
            '''  Future<Map<String, dynamic>> ${entry.key}(Map<String, dynamic> payload) =>
      runCommand(${_dartString(entry.value)}, payload);''',
      )
      .join('\n\n');

  final queryMethods = queries.entries
      .map(
        (entry) =>
            '''  Future<Map<String, dynamic>> ${entry.key}(Map<String, dynamic> payload) =>
      runQuery(${_dartString(entry.value)}, payload);''',
      )
      .join('\n\n');

  final publicMethods = publicRoutes.entries
      .map((entry) => _generateRouteMethod(entry.key, entry.value))
      .join('\n\n');

  return '''$generatedHeader
import '../entity_resource.dart';
import '../paths.dart';
import '../school_client.dart';

extension GeneratedSchoolClientEntities on SchoolClient {
$entityGetters
}

extension GeneratedSchoolClientCommands on SchoolClient {
$commandMethods
}

extension GeneratedSchoolClientQueries on SchoolClient {
$queryMethods
}

extension GeneratedSchoolClientPublic on SchoolClient {
$publicMethods
}
''';
}

String _generateRouteMethod(String key, Map<String, dynamic> binding) {
  final method = binding['method'];
  final path = binding['path'];
  if (method is! String || method.isEmpty) {
    throw StateError('Public binding $key is missing method');
  }
  if (path is! String || path.isEmpty) {
    throw StateError('Public binding $key is missing path');
  }

  final pathParams = binding['pathParams'];
  final names = pathParams is List
      ? pathParams.whereType<String>().where((name) => name.isNotEmpty).toList()
      : const <String>[];
  final hasBody = binding['requestSchemaName'] is String;
  final basePath = binding['basePath'] is String
      ? binding['basePath'] as String
      : 'core';

  final parameters = [
    for (final name in names) 'required String $name',
    if (hasBody) 'required Map<String, dynamic> payload',
  ];
  final signature = parameters.isEmpty ? '' : '{${parameters.join(', ')}}';
  final paramsMap = names.isEmpty
      ? 'const <String, String>{}'
      : '{${names.map((name) => '${_dartString(name)}: $name').join(', ')}}';
  final bodyArg = hasBody ? ',\n        body: payload' : '';

  return '''  Future<Map<String, dynamic>> $key($signature) =>
      requestRoute(
        ${_dartString(method)},
        resolveGeneratedPath(
          ${_dartString(path)},
          $paramsMap,
          basePath: ${_dartString(basePath)},
        )$bodyArg,
      );''';
}

Map<String, Map<String, dynamic>> _routeMap(Object? value) {
  if (value == null) {
    return const {};
  }
  if (value is! Map<String, dynamic>) {
    throw StateError('Bindings public section must be a JSON object');
  }

  return value.map((key, binding) {
    if (binding is! Map<String, dynamic>) {
      throw StateError('Public binding for $key must be a JSON object');
    }
    return MapEntry(key, binding);
  });
}

Map<String, Map<String, dynamic>> _entityMap(Object? value) {
  if (value is! Map<String, dynamic>) {
    throw StateError('Bindings entities must be a JSON object');
  }

  return value.map((key, binding) {
    if (binding is! Map<String, dynamic>) {
      throw StateError('Entity binding for $key must be a JSON object');
    }
    return MapEntry(key, binding);
  });
}

Map<String, String> _stringMap(Object? value, String fieldName) {
  if (value is! Map<String, dynamic>) {
    throw StateError('Bindings section must be a JSON object');
  }

  return value.map((key, binding) {
    if (binding is! Map<String, dynamic>) {
      throw StateError('Binding for $key must be a JSON object');
    }
    final fieldValue = binding[fieldName];
    if (fieldValue is! String) {
      throw StateError('Binding for $key is missing $fieldName');
    }
    return MapEntry(key, fieldValue);
  });
}

String _dartString(String value) => jsonEncode(value);
